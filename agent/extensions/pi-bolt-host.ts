/**
 * pi-bolt-host — lets pi-blackhole's mid-run (inline) compaction work under
 * Pi-Bolt without patching pi-blackhole.
 *
 * pi-blackhole's factory calls `installHostInlineCompactionAdapter()`, which
 * finds the host's `AgentSession` by walking `process.argv[1]` up to a
 * `package.json` named `@earendil-works/pi-coding-agent` and importing that
 * package's `dist/index.js`. Under Pi-Bolt `argv[1]` is the virtual
 * `/$bunfs/root/pi`, so no package root is found and the adapter reports
 * "host AgentSession module could not be resolved".
 *
 * This extension (a no-op unless compiled) builds a tiny stand-in host package
 * in `agent/cache/pi-bolt-host/` whose `dist/index.js` re-exports the *real*
 * `AgentSession` (the one pi's alias map hands extensions, stashed on
 * globalThis), and points `argv[1]` at it from this factory until this
 * extension's `session_start` handler. That window also covers later factories
 * and the `session_start` handlers of extensions discovered before this one
 * (discovery is raw readdir order, so which ones depends on the filesystem).
 * Nothing in this repo may read raw `argv[1]` to identify pi: use
 * `lib/runtime.ts` (`runningCompiled`, `piExecutable`, `originalEntry`), which
 * read the real entry recorded under `ORIGINAL_ENTRY_KEY`.
 *
 * Order matters: it must load before pi-blackhole. pi ranks auto-discovered
 * `agent/extensions/*` (rank 3) ahead of `settings.json` packages (rank 4) in
 * `package-manager.ts` `resourcePrecedenceRank`. A `-e npm:pi-blackhole` or a
 * settings `extensions` entry ranks earlier and would bypass this.
 */
import { existsSync, mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

import { AgentSession, type ExtensionAPI, VERSION } from "@earendil-works/pi-coding-agent";

import { agentDir } from "./lib/layout.js";
import { ORIGINAL_ENTRY_KEY, originalEntry, runningCompiled } from "./lib/runtime.js";

const HOST_KEY = "dotpi.pi-bolt-host.AgentSession";

/**
 * Writes `file` only when its content differs, via a pid-named temp + rename,
 * so a concurrent Pi-Bolt start (subagents launch several at once) never reads
 * a truncated file, and the synced tree is not touched on every start.
 */
function writeIfChanged(file: string, content: string): void {
	try {
		if (readFileSync(file, "utf8") === content) return;
	} catch {
		// Missing: write it.
	}
	const tmp = `${file}.${process.pid}`;
	writeFileSync(tmp, content);
	renameSync(tmp, file);
}

/**
 * pi's own `prepareCompaction`, which pi-blackhole uses to skip branches too
 * small to compact. Pi-Bolt's public barrel does not export it, so borrow the
 * bun pi install's copy (required beside Pi-Bolt anyway, see AGENTS.md), and
 * only when it is the same Pi version Pi-Bolt is built on. Otherwise
 * pi-blackhole fails open: compaction still works, but a too-small branch
 * surfaces as a retried "Nothing to compact" error instead of a quiet skip.
 */
function hostCompactionModule(): string | undefined {
	const bunInstall = process.env.BUN_INSTALL || join(homedir(), ".bun");
	const pkgRoot = join(bunInstall, "install", "global", "node_modules", "@earendil-works", "pi-coding-agent");
	try {
		const pkg = JSON.parse(readFileSync(join(pkgRoot, "package.json"), "utf8")) as { version?: string };
		const mod = join(pkgRoot, "dist", "core", "compaction", "index.js");
		return pkg.version === VERSION && existsSync(mod) ? mod : undefined;
	} catch {
		return undefined;
	}
}

/** Writes the stand-in host package; returns its fake CLI entry, or undefined on failure. */
function writeStandInHost(): string | undefined {
	try {
		const root = join(agentDir(), "cache", "pi-bolt-host");
		mkdirSync(join(root, "dist", "core", "compaction"), { recursive: true });
		writeIfChanged(
			join(root, "package.json"),
			`${JSON.stringify({ name: "@earendil-works/pi-coding-agent", version: "0.0.0-pi-bolt-host", type: "module", private: true })}\n`,
		);
		writeIfChanged(
			join(root, "dist", "index.js"),
			`// Generated by agent/extensions/pi-bolt-host.ts: the running Pi-Bolt's AgentSession.\nexport const AgentSession = globalThis[Symbol.for(${JSON.stringify(HOST_KEY)})];\n`,
		);
		const compaction = join(root, "dist", "core", "compaction", "index.js");
		const borrowed = hostCompactionModule();
		if (borrowed) {
			writeIfChanged(
				compaction,
				`// Generated by agent/extensions/pi-bolt-host.ts: pi ${VERSION}'s prepareCompaction.\nexport { prepareCompaction } from ${JSON.stringify(pathToFileURL(borrowed).href)};\n`,
			);
		} else {
			rmSync(compaction, { force: true });
		}
		const cli = join(root, "dist", "cli.js");
		writeIfChanged(cli, "// Generated by agent/extensions/pi-bolt-host.ts (stand-in entry; never executed, keep it comment-only).\n");
		return cli;
	} catch {
		return undefined;
	}
}

export default function (pi: ExtensionAPI): void {
	// originalEntry() reads the recorded real entry, so a reload never mistakes a leftover fake for script pi.
	if (!runningCompiled(originalEntry())) return;
	const cli = writeStandInHost();
	if (!cli) return;
	(globalThis as Record<symbol, unknown>)[Symbol.for(HOST_KEY)] = AgentSession;
	const original = originalEntry();
	if (original === undefined) return;
	// Recorded first, so runningCompiled()/piExecutable() keep answering for the real binary while argv[1] is faked.
	(globalThis as Record<symbol, unknown>)[ORIGINAL_ENTRY_KEY] = original;
	process.argv[1] = cli;
	pi.on("session_start", () => {
		if (process.argv[1] === cli) process.argv[1] = original;
	});
}
